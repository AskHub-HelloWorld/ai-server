"use strict";

/**
 * Format a byte count into a human-readable string.
 * @param {number} bytes
 * @returns {string}
 */
export function formatFileSize(bytes) {
  if (!bytes) return "";
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

/**
 * Extract a user-friendly message from an error value.
 * @param {unknown} error
 * @returns {string}
 */
export function formatError(error) {
  if (error instanceof Error) return error.message;
  return String(error);
}

/**
 * Promise-based sleep.
 * @param {number} ms
 * @returns {Promise<void>}
 */
export function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Scroll a container element to the very bottom.
 * @param {HTMLElement} el
 */
export function scrollToBottom(el) {
  el.scrollTop = el.scrollHeight;
}

/**
 * Determine a file-kind CSS class based on content type / filename.
 * @param {string} contentType
 * @param {string} filename
 * @returns {string}
 */
export function fileKindClass(contentType, filename) {
  const n = `${contentType} ${filename}`.toLowerCase();
  if (n.includes("pdf") || n.endsWith(".pdf")) return "file-kind-pdf";
  if (
    n.includes("spreadsheetml") ||
    n.endsWith(".xlsx") ||
    n.endsWith(".xls") ||
    n.endsWith(".csv")
  )
    return "file-kind-sheet";
  return "file-kind-doc";
}

/**
 * Return a human-readable file kind label.
 * @param {string} contentType
 * @param {string} filename
 * @returns {string}
 */
export function fileKindLabel(contentType, filename) {
  const n = `${contentType} ${filename}`.toLowerCase();
  if (n.includes("pdf")) return "PDF";
  if (
    n.includes("spreadsheetml") ||
    n.endsWith(".xlsx") ||
    n.endsWith(".xls") ||
    n.endsWith(".csv")
  )
    return "스프레드시트";
  if (
    n.includes("wordprocessingml") ||
    n.includes("presentationml") ||
    n.endsWith(".docx") ||
    n.endsWith(".doc") ||
    n.endsWith(".pptx") ||
    n.endsWith(".ppt")
  )
    return "문서";
  if (n.startsWith("image/")) return "이미지";
  if (n.startsWith("text/") || n.includes("json") || n.includes("xml"))
    return "텍스트";
  return "파일";
}

